import mongoose from "mongoose";
import { CASE_STATUSES } from "../models/Case.js";

/**
 * Input validation for case endpoints.
 * Returns an array of human-readable error strings (empty = valid),
 * following the same approach as auth.validator.js.
 */

const MAX_DESCRIPTION_LENGTH = 5000;

// Statuses a case may be created with; CLOSED/ARCHIVED only via update.
const CREATABLE_STATUSES = ["OPEN", "UNDER_INVESTIGATION"];

function validateTitle(title, errors) {
    if (typeof title !== "string" || title.trim().length === 0) {
        errors.push("title is required");
    } else if (title.trim().length < 3 || title.trim().length > 150) {
        errors.push("title must be between 3 and 150 characters");
    }
}

function validateDescription(description, errors) {
    if (description === undefined || description === null) return;
    if (typeof description !== "string") {
        errors.push("description must be a string");
    } else if (description.length > MAX_DESCRIPTION_LENGTH) {
        errors.push(`description must not exceed ${MAX_DESCRIPTION_LENGTH} characters`);
    }
}

function validateInvestigatorIds(investigators, errors) {
    if (investigators === undefined) return;
    if (!Array.isArray(investigators)) {
        errors.push("investigators must be an array of user ids");
        return;
    }
    for (const id of investigators) {
        if (!mongoose.isValidObjectId(id)) {
            errors.push(`investigators contains an invalid user id: ${id}`);
            break;
        }
    }
}

export function validateCaseCreation(body) {
    const errors = [];
    if (!body || typeof body !== "object") {
        return ["request body must be a JSON object"];
    }

    // createdBy and caseNumber are server-assigned; reject spoofing attempts.
    if (body.createdBy !== undefined) {
        errors.push("createdBy cannot be supplied");
    }
    if (body.caseNumber !== undefined) {
        errors.push("caseNumber is generated by the server");
    }

    validateTitle(body.title, errors);
    validateDescription(body.description, errors);
    validateInvestigatorIds(body.investigators, errors);

    if (body.status !== undefined && !CREATABLE_STATUSES.includes(body.status)) {
        errors.push(`status on creation must be one of: ${CREATABLE_STATUSES.join(", ")}`);
    }

    return errors;
}

export function validateCaseUpdate(body) {
    const errors = [];
    if (!body || typeof body !== "object") {
        return ["request body must be a JSON object"];
    }

    const allowedFields = ["title", "description", "status", "investigators"];
    const providedFields = Object.keys(body);

    if (providedFields.length === 0) {
        errors.push("at least one updatable field is required");
    }

    for (const field of providedFields) {
        if (!allowedFields.includes(field)) {
            errors.push(`field not updatable: ${field}`);
        }
    }

    if (body.title !== undefined) validateTitle(body.title, errors);
    if (body.description !== undefined) validateDescription(body.description, errors);
    if (body.investigators !== undefined) validateInvestigatorIds(body.investigators, errors);

    if (body.status !== undefined && !CASE_STATUSES.includes(body.status)) {
        errors.push(`status must be one of: ${CASE_STATUSES.join(", ")}`);
    }

    return errors;
}

export function validateCaseId(caseId) {
    return mongoose.isValidObjectId(caseId);
}
